st.subheader("Información del alimento")

columnas_categoricas = [
    'Food Product',
    'Main Ingredient',
    'Sweetener',
    'Fat/Oil',
    'Seasoning',
    'Allergens'
]



def obtener_categorias(nombre_columna):
    prefijo = nombre_columna + "_"

    return sorted([
        variable[len(prefijo):]
        for variable in variables
        if variable.startswith(prefijo)
    ])


categorias = {
    columna: obtener_categorias(columna)
    for columna in columnas_categoricas
}


col1, col2 = st.columns(2)


with col1:

    food_product = st.selectbox(
        'Food Product',
        categorias['Food Product']
    )

    main_ingredient = st.selectbox(
        'Main Ingredient',
        categorias['Main Ingredient']
    )

    sweetener = st.selectbox(
        'Sweetener',
        categorias['Sweetener']
    )


with col2:

    fat_oil = st.selectbox(
        'Fat/Oil',
        categorias['Fat/Oil']
    )

    seasoning = st.selectbox(
        'Seasoning',
        categorias['Seasoning']
    )

    allergens = st.selectbox(
        'Allergens',
        categorias['Allergens']
    )


datos = [[
    food_product,
    main_ingredient,
    sweetener,
    fat_oil,
    seasoning,
    allergens
]]


data = pd.DataFrame(
    datos,
    columns=columnas_categoricas
)

#Se realiza la preparación de datos
data_preparada=data.copy()

#En despliegue drop_first= False
data_preparada = pd.get_dummies(data_preparada, columns=['Food Product','Main Ingredient','Sweetener','Fat/Oil','Seasoning','Allergens'], drop_first=False, dtype=int)
data_preparada.head()

#EN LOS DESPLIEGUES NUNCA BORRAMOS DUMMIES, OSEA DROP FIRST SIEMPRE SIEMPRE SERÁ FALSO

#Se adicionan las columnas faltantes
#Porque por dummies y otras cosas (varaibles sin registros) se perdieron algunas columnas so con reindex las llenamos asi sea a punta de cero
data_preparada=data_preparada.reindex(columns=variables,fill_value=0)
data_preparada.head()

